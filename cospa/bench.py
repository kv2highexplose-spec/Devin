def cpu_lookup(key: str):
    key = key.lower()
    if key in CPU:
        return CPU[key]
    import re
    key = re.sub(r"(x3d)\d+$", r"\1", key)  # tolerate "9950x3d2" style typos
    if key in CPU:
        return CPU[key]
    # bare AMD mobile model like "5500u" -> try tier-prefixed keys
    m = re.fullmatch(r"(\d{4,5}[a-z0-9]*)", key)
    if m:
        for tier in ("3", "5", "7", "9"):
            hit = CPU.get(f"{tier} {key}")
            if hit:
                return hit
    return None

def gpu_lookup(key: str):
    return GPU.get(key.lower())
